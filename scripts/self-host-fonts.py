#!/usr/bin/env python3
"""Downloads the Google fonts the apps use into each app and writes fonts.css (run: python3 scripts/self-host-fonts.py lexica|landing)."""
import re, sys, urllib.request, os, hashlib
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36'
def get(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        d = r.read()
    return d if binary else d.decode()
def build(specs, outdir, cssname, subsets=('latin','latin-ext','vietnamese')):
    os.makedirs(outdir, exist_ok=True)
    css_out = ['/* Self-hosted so the build never depends on Google Fonts (see docs/HANDOFF.md). Generated by scripts/self-host-fonts.py. */']
    for family, query in specs:
        css = get('https://fonts.googleapis.com/css2?family=%s&display=swap' % query)
        for m in re.finditer(r'/\* ([\w-]+) \*/\s*(@font-face \{.*?\})', css, re.S):
            subset, block = m.group(1), m.group(2)
            if subset not in subsets: continue
            url = re.search(r'url\((https://[^)]+)\)', block).group(1)
            weight = re.search(r'font-weight: ([^;]+);', block).group(1).replace(' ', '-')
            style = re.search(r'font-style: (\w+);', block).group(1)
            slug = family.lower().replace(' ', '-')
            name = f'{slug}-{style}-{weight}-{subset}.woff2'
            path = os.path.join(outdir, name)
            if not os.path.exists(path):
                open(path, 'wb').write(get(url, True))
            block = re.sub(r'src: url\([^)]+\) format\(\'woff2\'\);', f"src: url('./{os.path.basename(outdir)}/{name}') format('woff2');", block)
            css_out.append(block)
    open(os.path.join(os.path.dirname(outdir), cssname), 'w').write('\n'.join(css_out) + '\n')
    print(outdir, len(css_out)-1, 'faces', sum(os.path.getsize(os.path.join(outdir,f)) for f in os.listdir(outdir))//1024, 'KB')
if __name__ == '__main__':
    which = sys.argv[1]
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'apps') + '/'
    if which == 'lexica':
        build([('Space Grotesk','Space+Grotesk:wght@300..700'),('JetBrains Mono','JetBrains+Mono:wght@100..800')], root+'lexica/app/fonts', 'fonts.css')
    if which == 'landing':
        build([('Space Grotesk','Space+Grotesk:wght@300..700'),('JetBrains Mono','JetBrains+Mono:wght@100..800'),('Be Vietnam Pro','Be+Vietnam+Pro:wght@400;500;600;700'),('Lora','Lora:ital,wght@0,400..700;1,400..700'),('Patrick Hand','Patrick+Hand')], root+'landing/src/app/fonts', 'fonts.css')
