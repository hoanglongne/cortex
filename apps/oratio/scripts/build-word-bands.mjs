// Builds src/lib/lexical-data.ts from the wordfreq English list (via the `nodewordfreq` package).
// Usage: node scripts/build-word-bands.mjs <path to nodewordfreq/data/large_en.msgpack.gz> <path to msgpackr>
// wordfreq: Copyright 2022 Robyn Speer. Code Apache-2.0; data CC BY-SA 4.0.
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { createRequire } from "node:module";

const [dataPath, msgpackrPath] = process.argv.slice(2);
const { unpack } = createRequire(import.meta.url)(msgpackrPath);
const lists = unpack(gunzipSync(readFileSync(dataPath)));
const bands = { a: [], b: [], c: [], d: [] };
for (let k = 1; k < lists.length; k++) {
  // List k holds the words at -(k-1) centibels: Zipf value = 9 - (k-1)/100
  const zipf = 9 - (k - 1) / 100;
  const band = zipf >= 5.5 ? "a" : zipf >= 4.7 ? "b" : zipf >= 4.0 ? "c" : zipf >= 3.3 ? "d" : null;
  if (!band) continue;
  for (const w of lists[k]) if (/^[a-z]+('[a-z]+)?$/.test(w)) bands[band].push(w);
}
const banner = `/**
 * Word frequency bands for English, generated by scripts/build-word-bands.mjs
 * from wordfreq (https://github.com/rspeer/wordfreq), Copyright 2022 Robyn
 * Speer. wordfreq's data is combined from several sources (Google Books
 * Ngrams, Wikipedia, subtitles, news, web text and more) and is shared under
 * CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/); this derived
 * list is shared under the same licence.
 *
 * a: Zipf >= 5.5 (the commonest words), b: 4.7 to 5.5, c: 4.0 to 4.7, d: 3.3 to 4.0.
 * A word in none of them is rarer than that.
 */
`;
const body = `export const BAND_WORDS = {\n${Object.entries(bands)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v.join(" "))},`)
  .join("\n")}\n} as const;\n`;
writeFileSync(new URL("../src/lib/lexical-data.ts", import.meta.url), banner + body);
