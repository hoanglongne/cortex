#!/usr/bin/env python3
"""Generates supabase/seed_studio_core_cards.sql from Lexica's core cards,
so Studio can write archetype variants (tech/business/student) for them.

Run from the repo root after changing apps/lexica/app/data/vocabCards.ts:
  python3 apps/cortex-core-api/scripts/build-studio-core-cards.py
"""
import json
import re
from pathlib import Path

SRC = Path('apps/lexica/app/data/vocabCards.ts')
OUT = Path('apps/cortex-core-api/supabase/seed_studio_core_cards.sql')

# Each card starts at its "id" key; the fields we need are plain JSON strings.
field = lambda name: re.compile(r'"' + name + r'":\s*("(?:[^"\\]|\\.)*"|\d+)')
FIELDS = ['word', 'elo', 'level', 'scenario', 'translationHint']

text = SRC.read_text(encoding='utf-8')
starts = [m.start() for m in re.finditer(r'"id":\s*"v\d+"', text)]
rows = []
seen = set()
for i, start in enumerate(starts):
    chunk = text[start: starts[i + 1] if i + 1 < len(starts) else len(text)]
    card_id = re.search(r'"id":\s*"(v\d+)"', chunk)[1]
    values = {}
    for name in FIELDS:
        m = field(name).search(chunk)
        if not m:
            break
        values[name] = json.loads(m[1])
    # The core list repeats a few cards verbatim; keep the first of each id.
    if len(values) == len(FIELDS) and card_id not in seen:
        seen.add(card_id)
        rows.append((card_id, values))

def q(s):
    return "'" + str(s).replace("'", "''") + "'"

lines = [
    '-- GENERATED by apps/cortex-core-api/scripts/build-studio-core-cards.py — do not edit by hand.',
    f'-- {len(rows)} Lexica core cards, the source for archetype variants.',
    'insert into studio_core_cards (id, word, scenario, translation_hint, level, elo) values',
    ',\n'.join(
        f"  ({q(cid)}, {q(v['word'].strip().lower())}, {q(v['scenario'])}, {q(v['translationHint'])}, {q(v['level'])}, {int(v['elo'])})"
        for cid, v in rows
    ),
    'on conflict (id) do update set word = excluded.word, scenario = excluded.scenario,',
    '  translation_hint = excluded.translation_hint, level = excluded.level, elo = excluded.elo;',
]
OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Wrote {OUT} ({len(rows)} cards)')
