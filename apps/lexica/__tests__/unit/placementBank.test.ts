/**
 * supabase/placement_bank.sql: the deck as the server's question bank for
 * verified scores (supabase/migration_placement.sql). Generated from the
 * same cards the app uses; this test fails when they drift apart.
 * Rewrite it with: WRITE_BANK=1 npx vitest run __tests__/unit/placementBank.test.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { expect, it } from 'vitest';
import { getAllCards } from '../../app/lib/content/repository';
import { blankPhrase } from '../../app/lib/placement/engine';
import { voiceFileName } from '../../app/lib/audio/voiceKey';

const FILE = path.join(__dirname, '../../supabase/placement_bank.sql');
const q = (s: string | null) => (s === null ? 'null' : `'${s.replace(/'/g, "''")}'`);

function build(): string {
    const seen = new Set<string>();
    const cards = getAllCards().filter((c) => (c.branch ?? 'cert') === 'cert' && !seen.has(c.id) && seen.add(c.id));
    const rows = cards.map((c) => {
        const word = c.word.toLowerCase();
        const audio = word.includes(' ') ? null : voiceFileName({ text: word });
        return `  (${q(c.id)}, ${q(word)}, ${q(c.translationHint)}, ${Math.round(c.elo)}, ${q(c.level)}, ${q(blankPhrase(c))}, ${q(audio)})`;
    });
    return [
        '-- GENERATED by apps/lexica/__tests__/unit/placementBank.test.ts — do not edit by hand.',
        `-- ${cards.length} Lexica cards: the question bank for verified vocabulary scores. Safe to re-run.`,
        '',
        'delete from public.lexica_placement_bank;',
        'insert into public.lexica_placement_bank (card_id, word, meaning, elo, level, phrase, audio) values',
        rows.join(',\n') + ';',
        '',
    ].join('\n');
}

it('placement_bank.sql matches the deck', () => {
    const sql = build();
    if (process.env.WRITE_BANK) fs.writeFileSync(FILE, sql);
    expect(fs.readFileSync(FILE, 'utf8')).toBe(sql);
});
