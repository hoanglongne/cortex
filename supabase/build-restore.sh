OUT=supabase/restore_all.sql
{
  echo "-- GENERATED by supabase/build-restore.sh — do not edit by hand."
  echo "-- Rebuilds the shared Supabase schema for Oratio, Lexica and Cortex Core API"
  echo "-- plus the IELTS question seed. Safe to re-run. Contains no user data."
  echo
  echo 'create extension if not exists "uuid-ossp";'
